class SSLClient {
    // public: // TEMPORARY
    SSL* ssl;
    BIO *rbio, *wbio;

    struct buf_t {
        char* buf = nullptr;
        size_t len;
        // TODO: make forward_list here
        void queue_data(const char* data, const size_t n){
            if (buf == nullptr)
                buf = (char*)malloc(len+n);
            else
                buf = (char*)realloc(buf, len+n);
            memcpy(buf+len, data, n);
            len += n;
        }
    };
    buf_t* to_encrypt_buf = new buf_t(); // data waiting to be encrypted by SSL
    buf_t* to_write_buf = new buf_t(); // data generated by SSL and waiting to be written to socket

    /// @brief on decrypted data available
    /// @param out buffer to write. sizeof(out) <= n unencrypted bytes
    void (*on_decrypted_cb)(const char* out, const size_t len);


    enum class SSLStatus {
        OK, WANT_IO, FAIL
    };
    static SSLStatus get_ssl_status(SSL* ssl, int n) {
        switch (SSL_get_error(ssl, n)) {
            case SSL_ERROR_NONE:
                return SSLStatus::OK;
            case SSL_ERROR_WANT_WRITE:
            case SSL_ERROR_WANT_READ:
                return SSLStatus::WANT_IO;
            case SSL_ERROR_ZERO_RETURN:
            case SSL_ERROR_SYSCALL:
            default:
                return SSLStatus::FAIL;
        }
    }

    /// @brief process data: to_encrypt_buf -> SSL encryption -> to_write_buf
    /// @return true on fail
    bool do_encrypt(){
        while (to_encrypt_buf->len > 0){
            int n = SSL_write(ssl, to_encrypt_buf->buf, to_encrypt_buf->len);
            // there are data to encrypt
            if (n > 0){
                // move remaining after SSL_write bytes to begin of the to_encrypt_buf
                if (n < to_encrypt_buf->len)
                    memmove(to_encrypt_buf->buf, to_encrypt_buf->buf+n, to_encrypt_buf->len-n);
                to_encrypt_buf->len -= n;
                // free empty memory
                to_encrypt_buf->buf = (char*)realloc(to_encrypt_buf->buf, to_encrypt_buf->len);

                // write data to the to_write_buf
                char buf[256];
                do {
                    n = BIO_read(wbio, buf, sizeof(buf));
                    if (n > 0)
                        to_write_buf->queue_data(buf, n);
                    else if (!BIO_should_retry(wbio))
                        return true;
                } while (n > 0);
            }
            // end of to_encrypt_buf;
            if (n == 0) break;
        }
        return 0;
    }


    
public:
    
    SSLClient(SSL_CTX* ctx, void (*on_decrypted_cb)(const char* out, const size_t len)) {
        rbio = BIO_new(BIO_s_mem());
        wbio = BIO_new(BIO_s_mem());
        ssl = SSL_new(ctx);
        SSL_set_accept_state(ssl); /* ??? (c) example: sets ssl to work in server mode. */
        SSL_set_bio(ssl, rbio, wbio);

        this->on_decrypted_cb = on_decrypted_cb;
    }

    /// @brief do SSL handshake
    /// @return SSLStatus::OK - handshake done.
    SSLStatus do_handshake() {
        int n = SSL_do_handshake(ssl);
        if (get_ssl_status(ssl, n) == SSLStatus::WANT_IO) {
            char buf[256];
            do {
                n = BIO_read(wbio, buf, sizeof(buf));
                printf("n: %d\n", n);
                if (n > 0)
                    to_write_buf->queue_data(buf, n);
                else if (n == 0)
                    return SSLStatus::WANT_IO;
                else if (!BIO_should_retry(wbio))
                    return SSLStatus::FAIL;
            } while (n > 0);
        }
        return SSLStatus::OK;
    }

    /// @brief encrypt and write data
    /// @param in unencrypted input
    /// @param len size of *in
    void queue_write(const char* in, const size_t len){
        to_encrypt_buf->queue_data(in, len);
    }

    

    ~SSLClient(){
        SSL_free(ssl);
        free(to_write_buf);
        free(to_encrypt_buf);
    }

    static void on_read_after_handshake(uv_stream_t* client, ssize_t nread,
                                        const uv_buf_t* rbuf) {
        // if OK
        if (nread > 0) {
            SSLClient& ssl_client = *static_cast<SSLClient*>(client->data);
            char* p_data = rbuf->base;
            while (nread > 0) {
                // pass data
                int n = BIO_write(ssl_client.rbio, p_data, nread);
                if (n <= 0) return;  // on BIO error
                p_data += n;
                nread -= n;

                // try decoding
                do {
                    char buf[256];
                    n = SSL_read(ssl_client.ssl, buf, sizeof(buf));
                    // call user callback
                    if (n > 0)
                        ssl_client.on_decrypted_cb(buf, n);
                } while (n > 0);
                SSLStatus ret = get_ssl_status(ssl_client.ssl, n);
                if (ret == SSLStatus::WANT_IO){
                    do {
                        char buf[256];
                        n = BIO_read(ssl_client.wbio, buf, sizeof(buf));
                        if (n > 0)
                            ssl_client.to_write_buf->queue_data(buf, n);
                        else if (!BIO_should_retry(ssl_client.wbio))
                            return;
                    } while (n > 0);
                }
            }
        }
        // if ERROR
        if (nread < 0) {
            warnx("nread < 0");
            if (nread != UV_EOF)
                warnx("read error (%ld) %s", nread, uv_err_name(nread));
            uv_close((uv_handle_t*)client, on_connection_close);
        }
        // if nread <= 0
        free(rbuf->base);
    }
    static void on_read_before_handshake(uv_stream_t* client, ssize_t nread,
                                  const uv_buf_t* rbuf) {
        // if OK
        if (nread > 0) {
            SSLClient& ssl_client = *static_cast<SSLClient*>(client->data);
            char* p_data = rbuf->base;
            while (nread > 0){
                // pass data
                int n = BIO_write(ssl_client.rbio, p_data, nread);
                if (n <= 0) return; // on BIO error
                p_data += n;
                nread -= n;

                // try handshake
                switch (ssl_client.do_handshake()) {
                    case SSLStatus::WANT_IO:
                        continue;
                    case SSLStatus::FAIL:
                        warnx("ssl handshake failed");
                        return;
                    case SSLStatus::OK:
                        printf("%d\n", uv_read_stop(client));
                        printf("%d\n", uv_read_start((uv_stream_t*)client, on_alloc,
                                      on_read_after_handshake));
                }
            }
        }
        // if ERROR
        if (nread < 0){
            warnx("nread < 0");
            if (nread != UV_EOF)
                warnx("read error (%ld) %s", nread, uv_err_name(nread));
            uv_close((uv_handle_t*)client, on_connection_close);
        }
        // if nread <= 0
        free(rbuf->base);
    }
};

