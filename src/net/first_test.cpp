int main(){
    uv_loop_t* main_loop = uv_default_loop();

    uv_signal_t sigint;
    uv_signal_init(main_loop, &sigint);
    uv_signal_start(&sigint, on_sigint_received, SIGINT);

    ssl_init("server.crt", "server.key");

    uv_tcp_t server;
    uv_tcp_init(main_loop, &server);
    struct sockaddr_in addr;
    uv_ip4_addr("0.0.0.0", 20202, &addr);
    uv_tcp_bind(&server, (const struct sockaddr*)&addr, 0);
    int r = uv_listen((uv_stream_t*)&server, DEFAULT_BACKLOG, on_new_connection);
    if (r) {
        warnx("tcp listen error %s (%d)", uv_strerror(r));
        return 1;
    }

    printf("running the loop\n");
    int exit_code = uv_run(main_loop, UV_RUN_DEFAULT);


    printf("the loop is over (%d)", exit_code);
    // free(main_loop); // dont free the default loop
    main_loop = nullptr;
    return exit_code;
}

void _on_uv_walk(uv_handle_t* handle, void* arg) { uv_close(handle, NULL); }
void full_close_uv_loop(uv_loop_t* loop) {
    // close all handlers first
    uv_stop(loop);
    uv_walk(loop, _on_uv_walk, NULL);
    uv_run(loop, UV_RUN_DEFAULT);  // run loop one time
    // close the loop
    uv_loop_close(loop);
}
void on_sigint_received(uv_signal_t* handle, int sig) {
    printf("received signal %d\n", sig);
    full_close_uv_loop(handle->loop);
}

void on_alloc(uv_handle_t* handle, size_t suggested_size, uv_buf_t* buf) {
    buf->base = (char*)malloc(suggested_size);
    buf->len = suggested_size;
}

void on_new_connection(uv_stream_t* server, int status){
    if (status < 0){
        warnx("connection accept error (%d) %s", status, uv_strerror(status));
        return;
    }
    uv_tcp_t* client = (uv_tcp_t*)malloc(sizeof(uv_tcp_t));
    uv_tcp_init(server->loop, client);
    if (uv_accept(server, (uv_stream_t*)client) == 0){
        printf("new client\n");
        SSLClient* ssl_client = new SSLClient(ssl_context, print_decrypted_data);
        client->data = ssl_client;
        uv_read_start((uv_stream_t*) client, on_alloc, SSLClient::on_read_before_handshake);
    }
}
void on_connection_close(uv_handle_t* handle) {
    printf("client disconnected\n");
    delete (SSLClient*)handle->data;
    free(handle);
}

void ssl_init(const char* certsfile, const char* keyfile) {
    SSL_library_init();
    OpenSSL_add_all_algorithms();
    const unsigned char session_cache_id[] = "SSL_TEST_01_VERSIYA";
    ssl_context = SSL_CTX_new(TLS_server_method());
    if (ssl_context == nullptr) {
        ERR_print_errors_fp(stderr);
        errx(EXIT_FAILURE, "Failed to create server SSL_CTX");
    }
    // configure SSL_CTX
    if (!SSL_CTX_set_min_proto_version(ssl_context, TLS1_3_VERSION)) {
        SSL_CTX_free(ssl_context);
        ERR_print_errors_fp(stderr);
        errx(EXIT_FAILURE,
             "Failed to set the minimum TLS protocol version (hardcoded "
             "TLS1.3)");
    }
    uint64_t opts = 0;
    opts |= SSL_OP_IGNORE_UNEXPECTED_EOF;
    opts |= SSL_OP_NO_RENEGOTIATION;
    opts |= SSL_OP_CIPHER_SERVER_PREFERENCE;
    opts |= SSL_OP_ALL | SSL_OP_NO_SSLv2 | SSL_OP_NO_SSLv3;
    SSL_CTX_set_options(ssl_context, opts);
    if (SSL_CTX_use_certificate_chain_file(ssl_context, certsfile) <= 0) {
        SSL_CTX_free(ssl_context);
        ERR_print_errors_fp(stderr);
        errx(EXIT_FAILURE, "Failed to load the server certificate chain file");
    }
    if (SSL_CTX_use_PrivateKey_file(ssl_context, keyfile, SSL_FILETYPE_PEM) <= 0) {
        SSL_CTX_free(ssl_context);
        ERR_print_errors_fp(stderr);
        errx(EXIT_FAILURE,
             "Error loading the server private key file, "
             "possible key/cert mismatch???");
    }
    // Enable SSL_SESSION caching
    SSL_CTX_set_session_id_context(ssl_context, session_cache_id,
                                   sizeof(session_cache_id));
    SSL_CTX_set_session_cache_mode(ssl_context, SSL_SESS_CACHE_SERVER);
    // How many client TLS sessions to cache.
    // The default is 20k (SSL_SESSION_CACHE_MAX_SIZE_DEFAULT)
    SSL_CTX_sess_set_cache_size(ssl_context, 64);
    // t in seconds. the default is two hours
    SSL_CTX_set_timeout(ssl_context, 3600);

    // Explicitly disable clients sertificate store
    SSL_CTX_set_verify(ssl_context, SSL_VERIFY_NONE, NULL);
}